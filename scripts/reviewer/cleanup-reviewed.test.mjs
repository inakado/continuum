import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile,rm,mkdir,symlink,unlink} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {downloadSolution,writeJson,sha256} from './client.mjs';
import {cleanupReviewed} from './cleanup-reviewed.mjs';
const id='11111111-1111-4111-8111-111111111111';
test('draft and unknown publication retain all inputs; matching published revision cleans only managed files',async()=>{
 const root=await mkdtemp(join(tmpdir(),'reviewer-clean-test-')),directory=join(root,id);
 try {
  const source={id,assignmentId:id,recipientId:id,versionId:id,taskId:id,number:23,title:'Задача',statement:'Условие',maxPoints:2,source:null,sourceRevision:1,locked:false,review:null,publishedRevision:null,photos:[{id,contentType:'image/jpeg',sizeBytes:3,sha256:sha256('abc'),downloadPath:`/reviewer/v1/solutions/${id}/photos/${id}?sourceRevision=1`}],images:[]};
  const manifestPath=await downloadSolution(async path=>path.endsWith(id)?source:new Response('abc'),id,directory,'https://example.test');
  const manifest=JSON.parse(await readFile(manifestPath,'utf8'));
  await writeJson(join(directory,'managed.json'),{owner:'continuum-reviewer-pilot-v1',solutionId:id,sourceRevision:1});
  const pdfPath=join(directory,'review.pdf'),operationPath=join(directory,'operation.json');
  await writeFile(pdfPath,'%PDF-report');
  const operation={reportId:id,input:{solutionId:id,sourceRevision:1,points:2,sha256:sha256('%PDF-report')}};
  await writeJson(operationPath,operation);
  const args={root,directory,operationPath,pdfPath};
  await assert.rejects(cleanupReviewed(args),/Нет подтверждённой/);
  assert.equal(await readFile(join(directory,manifest.photos[0].path),'utf8'),'abc');
  await writeJson(operationPath,{...operation,review:{id,revision:1,reportId:id,sourceRevision:1,points:2,authorUserId:id,savedAt:'2026-10-31T00:00:00Z'},publicationItem:{reviewId:id,reviewRevision:1,sourceRevision:1,expectedPublishedRevision:null}});
  const publication={id,publishedAt:'2026-10-31T00:00:00Z',items:[{reviewId:id,reviewRevision:1,solutionId:id,points:2}]};
  await assert.rejects(cleanupReviewed(args));
  await assert.rejects(cleanupReviewed({...args,publication:{...publication,items:[{...publication.items[0],reviewRevision:2}]}}),/публикации/);
  assert.equal(await readFile(pdfPath,'utf8'),'%PDF-report');
  const evaluation='Разбор записей ученика';
  await writeFile(join(directory,'evaluation.json'),evaluation);
  await writeJson(join(directory,'managed.json'),{owner:'continuum-reviewer-pilot-v1',solutionId:id,sourceRevision:1,evaluationHash:sha256(evaluation)});
  const build=join(directory,'.review-build-orphan'); await mkdir(build);
  await writeFile(join(build,'review.tex'),'Текст ученика'); await writeFile(join(build,'review.aux'),'aux');
  await writeFile(join(directory,'teacher-note.txt'),'Не удалять');
  const photoPath=join(directory,manifest.photos[0].path),outside=join(root,'original-photo.jpg');
  await writeFile(outside,'abc'); await unlink(photoPath); await symlink(outside,photoPath);
  await assert.rejects(cleanupReviewed({...args,publication}),/Небезопасный/);
  assert.equal(await readFile(outside,'utf8'),'abc');
  assert.equal(await readFile(pdfPath,'utf8'),'%PDF-report');
  await unlink(photoPath); await writeFile(photoPath,'abc');
  const result=await cleanupReviewed({...args,publication});assert.equal(result.removedFiles,5);
  await assert.rejects(readFile(pdfPath),/ENOENT/);
  await assert.rejects(readFile(join(directory,manifest.photos[0].path)),/ENOENT/);
  assert.equal(await readFile(join(directory,'teacher-note.txt'),'utf8'),'Не удалять');
  await assert.rejects(readFile(join(directory,'evaluation.json')),/ENOENT/);
  await assert.rejects(readFile(join(build,'review.tex')),/ENOENT/);
  assert.equal(JSON.parse(await readFile(result.receiptPath,'utf8')).review.points,2);
  assert.equal((await cleanupReviewed({...args,publication})).removedFiles,0);
  await assert.rejects(cleanupReviewed({...args,directory:root}),/управляемой/);
 } finally {await rm(root,{recursive:true,force:true});}
});
