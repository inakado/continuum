// Authoring only: node build-motion-geometry.mjs /path/to/anatomy/kit/iso-kit.mjs
// Anatomy Figure: a sliding laboratory carriage, fixed post and coordinate axis.
// 47 physical parts: 8 foot pads, bed + trim, 4 bed screws, 2 rail seats,
// 2 rails + 4 screws, 2 stops + 1 visible buffer + 4 screws, reference foot,
// post + cap + 2 screws, 4 bearing blocks, carriage bed + cover,
// inlay + index + index drop, 4 cover screws.
// All are rounded prisms; no pipes, rotating bodies or external runtime kit.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { MOTION_START } from './motion-model.ts';

if (!process.argv[2]) throw new Error('Pass the anatomy kit/iso-kit.mjs path');
const k = await import(pathToFileURL(process.argv[2]).href);
const base = { x: 0, y: -62, w: 550, d: 124, r: 10 };
const P = k.fitProjection([...k.boxCorners(base, 0, 22), [40, 48, 108], [500, -35, 86]], 900, 300, { pad: 36, azimuth: 74, elevation: 26 });
const at = (p) => k.iso(p, P);
const line = (d, options) => k.lineSvg(d, { tone: 'lo', ...options });
let count = 0;
const slab = (x, y, w, d, z, h, r = 1, className = '') => {
  count++;
  return k.solidSvg(k.slabOf({ x, y, w, d, r }, z, h, P, 5, Math.min(h / 4, 0.8)), { tone: 'mid', className });
};
const screw = (x, y, z) => slab(x - 1.6, y - 1.6, 3.2, 3.2, z, 0.8, 0.6, 'fastener');
const stationary = [];
stationary.push(`<path class="iso-halo" d="${k.haloOf(base, 0, 4, P)}"/>`);
for (const [x, y] of k.corners(base, 24).sort((a, b) => k.depthOf([...a, 0], P) - k.depthOf([...b, 0], P))) {
  stationary.push(slab(x - 9, y - 9, 18, 18, 0, 3, 3, 'rubber'), slab(x - 7, y - 7, 14, 14, 3, 5, 2));
}
stationary.push(slab(0, -62, 550, 124, 8, 11, 10), slab(1, -61, 548, 122, 19, 3, 9));
stationary.push(line(k.planOutline(k.insetPlan(base, 6), 22, P)));
for (const [x, y] of k.corners(base, 13)) stationary.push(screw(x, y, 22));
for (const y of [-24, 18]) {
  stationary.push(slab(70, y - 3, 455, 12, 22, 4, 2), slab(70, y, 455, 6, 26, 8, 1, 'rail'));
  for (const x of [79, 516]) stationary.push(screw(x, y + 3, 34));
}
for (const x of [70, 517]) {
  stationary.push(slab(x, -32, 8, 64, 22, 17, 2));
  if (x === 70) stationary.push(slab(x + 8, -29, 3, 58, 28, 10, 1, 'rubber'));
  for (const y of [-27, 27]) stationary.push(screw(x + 4, y, 39));
}
const track = stationary.join('');
// The coordinate axis is an explanatory overlay on white, clear of the platform.
const marks = [];
for (let x = 40; x <= 520; x += 60) marks.push(line(k.segment([x, 96, 0], [x, x === 40 ? 103 : 101, 0], P)));
const axis = `<g class="coordinate-axis">${line(k.segment([40, 96, 0], [552, 96, 0], P))}${marks.join('')}<path class="motion-axis-tip" d="${k.onTop([[545, 92], [552, 96], [545, 100]], 0, P, true)}"/></g>`;
const referenceProjection = `<path class="motion-reference-projection" d="${k.segment([40, 62, 8], [40, 96, 0], P)}"/>`;

// Fixed post is outside the carriage's swept volume, bolted to the bed.
stationary.push(slab(29, 8, 22, 24, 22, 5, 3, 'reference'));
stationary.push(slab(36, 15, 8, 10, 27, 72, 1, 'reference'));
stationary.push(slab(32, 12, 16, 16, 99, 5, 2, 'reference'));
for (const x of [33, 47]) stationary.push(screw(x, 28, 27));

const carriage = [];
const carriageCornerRadius = 5;
for (const y of [-26, 16]) for (const x of [79, 121]) carriage.push(slab(x, y, 12, 12, 34, 9, 2, 'bearing'));
carriage.push(slab(72, -36, 72, 72, 43, 7, carriageCornerRadius, 'carriage'));
carriage.push(slab(75, -33, 66, 66, 50, 20, 5, 'carriage'));
carriage.push(slab(82, -26, 52, 52, 70, 1, 3, 'inlay'));
// Index tongue touches the carriage; a dashed projection continues to the axis.
const indicator = [slab(106, 33, 4, 16, 49, 2, 0.5, 'carriage'), slab(106, 47, 4, 2, 23, 26, 0.4, 'carriage')];
for (const [x, y] of [[79, -29], [137, -29], [79, 29], [137, 29]]) carriage.push(screw(x, y, 70));
const moving = [...carriage, ...indicator];
const zero = at([0, 0, 0]);
const unit = at([60, 0, 0]);
const output = {
  stationary: stationary.join(''), moving: `<g transform="${k.translateAlong(P, [40 + MOTION_START * 60 - 108, 0, 0])}">${moving.join('')}</g>`,
  axis: referenceProjection + axis,
  // Fixed zero x=40 lies on the post's axis; 60 world units per metre.
  travelPerMetre: [unit[0] - zero[0], unit[1] - zero[1]],
  referenceAnchor: at([40, 20, 104]),
  zeroAnchor: at([40, 96, 0]),
  axisAnchor: at([545, 96, 0]),
  coordinateAxis: { origin: at([40, 96, 0]), pointer: at([40 + MOTION_START * 60, 48, 23]) },
  track,
  carriage: carriage.join(''),
  carriageDimensions: { restX: 108, width: 72, length: 72, pointZ: 71.4, cornerRadius: carriageCornerRadius },
  projection: P,
  worldUnitsPerMetre: 60,
};
writeFileSync(new URL('./motion-geometry.generated.ts', import.meta.url), `// Generated by build-motion-geometry.mjs with the anatomy kit. Do not edit paths.\nexport const motionGeometry = ${JSON.stringify(output)} as const;\n`);
console.log(`Anatomy Figure: ${count} solids; geometry generated`);
