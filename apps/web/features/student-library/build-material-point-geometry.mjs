// Anatomy Figure: the same carriage and bed, with an adjustable clear aperture.
// 52 visible parts: shared 29-part track, 11-part carriage, 11 post parts,
// and one variable-length crossbar. Every foot stays outside the clear opening.
// node build-material-point-geometry.mjs /path/to/anatomy/kit/iso-kit.mjs
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { motionGeometry as source } from './motion-geometry.generated.ts';

if (!process.argv[2]) throw new Error('Pass the anatomy kit/iso-kit.mjs path');
const k = await import(pathToFileURL(process.argv[2]).href);
const P = source.projection;
const gateX = 360;
const opening = { min: 56, max: 84, initial: 64 };
const postCornerRadius = 1;
const slab = (x, y, w, d, z, h, r = 1) => k.solidSvg(k.slabOf({ x, y, w, d, r }, z, h, P, 5, Math.min(h / 4, .7)), { tone: 'mid' });
function post(side) {
  const half = opening.initial / 2;
  const footY = side < 0 ? -half - 12 : half;
  const y = side < 0 ? -half - 8 : half;
  const out = [slab(gateX - 5, footY, 20, 12, 22, 4, 2)];
  out.push(slab(gateX, y, 10, 8, 26, 40, postCornerRadius));
  out.push(slab(gateX, y, 10, 8, 66, 40, postCornerRadius));
  out.push(slab(gateX - 2, y, 14, 8, 106, 4, 1));
  const screwY = side < 0 ? footY + 2 : footY + 10;
  // The left fastener of the far foot is occluded by its upright.
  for (const x of side < 0 ? [gateX + 12] : [gateX - 2, gateX + 12]) out.push(slab(x - 1.2, screwY - 1.2, 2.4, 2.4, 26, .7, .5));
  return out.join('');
}
const origin = k.iso([0, 0, 0], P);
const axes = [[1, 0, 0], [0, 1, 0], [0, 0, 1]].map((point) => { const p = k.iso(point, P); return [p[0] - origin[0], p[1] - origin[1]]; });
const output = {
  back: post(-1), front: post(1), view: { origin, axes },
  layout: { ...source.carriageDimensions, gateX, postCornerRadius, startX: 145, endX: 460, opening, worldUnitsPerMetre: source.worldUnitsPerMetre },
};
writeFileSync(new URL('./material-point-geometry.generated.ts', import.meta.url), `// Generated by build-material-point-geometry.mjs with anatomy.\nexport const materialPointGeometry = ${JSON.stringify(output)} as const;\n`);
console.log('Anatomy Figure: 52 solids; material point geometry generated');
