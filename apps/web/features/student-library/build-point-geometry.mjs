// Minimal mathematical axes in the existing anatomy camera.
// Authoring only: node build-point-geometry.mjs /path/to/anatomy/kit/iso-kit.mjs
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

if (!process.argv[2]) throw new Error('Pass the anatomy kit/iso-kit.mjs path');
const k = await import(pathToFileURL(process.argv[2]).href);
const UNIT = 45;
const width = 500;
const height = 440;
const world = ([x, y, z]) => [y * UNIT, x * UNIT, z * UNIT + 3];
const corners = [];
for (const x of [0, 6.6]) for (const y of [0, 6.6]) for (const z of [0, 6.6]) corners.push(world([x, y, z]));
const P = k.fitProjection(corners, width, height, { pad: 34, azimuth: 110, elevation: 25 });
const at = (point) => k.iso(world(point), P);
const origin = at([0, 0, 0]);
const axes = [[1, 0, 0], [0, 1, 0], [0, 0, 1]].map((point) => { const p = at(point); return [p[0] - origin[0], p[1] - origin[1]]; });
const art = [];
const tips = [[6.38, 0, 0], [0, 6.38, 0], [0, 0, 6.38]];
tips.forEach((tip, i) => {
  const end = at(tip);
  const [dx, dy] = axes[i];
  const length = Math.hypot(dx, dy);
  const ux = dx / length, uy = dy / length;
  const back = [end[0] - ux * 7, end[1] - uy * 7];
  art.push(`<path class="point-axis-line" d="M${origin.join(' ')}L${back.join(' ')}" fill="none" stroke="#8393ad" stroke-width="1.1" stroke-linecap="round"/>`);
  art.push(`<path class="point-axis-tip" d="M${end.join(' ')}L${back[0] - uy * 2.5} ${back[1] + ux * 2.5}L${back[0] + uy * 2.5} ${back[1] - ux * 2.5}Z" fill="#8393ad"/>`);
});
const output = { art: art.join(''), view: { origin, axes }, labels: tips.map(at), width, height };
writeFileSync(new URL('./point-geometry.generated.ts', import.meta.url), `// Generated by build-point-geometry.mjs using anatomy. Do not edit paths.\nexport const pointGeometry = ${JSON.stringify(output)} as const;\n`);
console.log('Three minimal coordinate axes generated in the anatomy camera');
